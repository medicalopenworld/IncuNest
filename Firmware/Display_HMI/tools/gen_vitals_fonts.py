"""Generates the LVGL fonts of the pulse-oximetry readings (lock screen) from
Roboto Flex, the variable font of Roboto (SIL Open Font License 1.1).

Why a script and not lv_font_conv: the readings need only a handful of glyphs
of one instance of a variable font, and lv_font_conv cannot pin variation axes.
This writes the same C structures lv_font_conv does (LVGL 8, 4 bpp, plain
bitmaps, no kerning), with FreeType through Pillow as the rasterizer.

Three fonts, written to src/ui/assets/:

  ui_font_vitals_value   48 px  wght 500  opsz 48   "0123456789.-"
  ui_font_vitals_small   20 px  wght 400  opsz 14   "0123456789.-"
  ui_font_vitals_title   14 px  wght 400  opsz 14   the letters of the titles

Roboto's digits all have the same advance (tabular figures), so a reading does
not move sideways when it changes; Montserrat's do not.

The line box of each font is the ink box of its glyphs (ascent of the tallest
glyph, descent of the lowest), not the font's own ascender and descender. A
label is then exactly as tall as its text, and three rows fit in the 105 px of
the frame without placing each one by a hand-measured offset.

Candidates kept in reserve, same script, other axes for the value font:
  Roboto Condensed Medium     --value-axes wght=500,wdth=75,opsz=48
  Roboto Condensed SemiBold   --value-axes wght=600,wdth=75,opsz=48

Needs Pillow and fontTools. Use (from Display_HMI/):
  python tools/gen_vitals_fonts.py --ttf <path>/RobotoFlex-Regular.ttf
"""

import argparse
import io
import os

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "src", "ui", "assets")
DIGITS = "0123456789.-"
TITLES = sorted(set("PR" "SpO2" "PI %"))


def parse_axes(text):
    return {k: float(v) for k, v in (item.split("=") for item in text.split(","))}


def instance(ttf_path, axes):
    """A static instance of the variable font: the given axes, the rest at default."""
    font = TTFont(ttf_path)
    pins = {a.axisTag: a.defaultValue for a in font["fvar"].axes}
    pins.update(axes)
    instancer.instantiateVariableFont(font, pins, inplace=True)
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue(), font


def glyph(pil_font, ch):
    """4 bpp coverage of one glyph and its ink box, relative to the pen on the baseline."""
    size = pil_font.size
    ox, oy = size, 2 * size                       # pen position inside a roomy canvas
    img = Image.new("L", (3 * size, 3 * size), 0)
    ImageDraw.Draw(img).text((ox, oy), ch, font=pil_font, fill=255, anchor="ls")
    quant = img.point(lambda v: (v + 8) // 17)    # 0..15, what LVGL will store
    box = quant.getbbox()                         # the ink that survives 4 bpp
    w = h = ofs_x = ofs_y = 0
    nibbles = []
    if box:
        x0, y0, x1, y1 = box
        w, h, ofs_x, ofs_y = x1 - x0, y1 - y0, x0 - ox, oy - y1
        nibbles = list(quant.crop(box).tobytes())
    return {
        "ch": ch,
        "adv": int(pil_font.getlength(ch) * 16 + 0.5),
        "w": w, "h": h, "ofs_x": ofs_x, "ofs_y": ofs_y,
        "nibbles": nibbles,
    }


def pack(nibbles):
    """Nibbles to bytes, high nibble first, as bitmap_format 0 of LVGL stores 4 bpp."""
    if len(nibbles) % 2:
        nibbles = nibbles + [0]
    return [(nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2)]


def write_font(name, ttf_bytes, ttfont, size, chars, axes, source_name):
    pil_font = ImageFont.truetype(io.BytesIO(ttf_bytes), size)
    chars = sorted(chars)
    glyphs = [glyph(pil_font, c) for c in chars]
    ascent = max(g["ofs_y"] + g["h"] for g in glyphs)
    descent = max(0, max(-g["ofs_y"] for g in glyphs if g["h"]))
    advances = {g["adv"] for g in glyphs if g["ch"].isdigit()}
    copyright_line = ""
    for rec in ttfont["name"].names:
        if rec.nameID == 0 and rec.platformID == 3:
            copyright_line = rec.toUnicode().strip()
            break

    out = []
    out.append("/*******************************************************************************")
    out.append(" * %s: %s, %d px, 4 bpp, glyphs \"%s\"" % (name, source_name, size, "".join(chars)))
    out.append(" * Axes: %s (the rest at their default)" % ", ".join("%s=%g" % kv for kv in sorted(axes.items())))
    out.append(" * Generated by tools/gen_vitals_fonts.py. Do not edit by hand.")
    out.append(" *")
    out.append(" * %s" % copyright_line)
    out.append(" * Licensed under the SIL Open Font License, Version 1.1:")
    out.append(" * https://openfontlicense.org")
    out.append(" ******************************************************************************/")
    out.append("")
    out.append("#include \"lvgl.h\"")
    out.append("")
    out.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    index = 0
    for g in glyphs:
        data = pack(g["nibbles"])
        g["index"] = index
        index += len(data)
        out.append("    /* U+%04X \"%s\" */" % (ord(g["ch"]), g["ch"]))
        for i in range(0, len(data), 12):
            out.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    out.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,")
    for g in glyphs:
        out.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}," % (
            g["index"], g["adv"], g["w"], g["h"], g["ofs_x"], g["ofs_y"]))
    out.append("};")
    out.append("")
    first, last = ord(chars[0]), ord(chars[-1])
    out.append("static const uint16_t unicode_list_0[] = {")
    out.append("    " + ", ".join("0x%x" % (ord(c) - first) for c in chars))
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    out.append("    {")
    out.append("        .range_start = %d, .range_length = %d, .glyph_id_start = 1," % (first, last - first + 1))
    out.append("        .unicode_list = unicode_list_0, .glyph_id_ofs_list = NULL, .list_length = %d," % len(chars))
    out.append("        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY")
    out.append("    }")
    out.append("};")
    out.append("")
    out.append("static lv_font_fmt_txt_glyph_cache_t cache;")
    out.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    out.append("    .glyph_bitmap = glyph_bitmap,")
    out.append("    .glyph_dsc = glyph_dsc,")
    out.append("    .cmaps = cmaps,")
    out.append("    .kern_dsc = NULL,")
    out.append("    .kern_scale = 0,")
    out.append("    .cmap_num = 1,")
    out.append("    .bpp = 4,")
    out.append("    .kern_classes = 0,")
    out.append("    .bitmap_format = 0,")
    out.append("    .cache = &cache")
    out.append("};")
    out.append("")
    out.append("const lv_font_t %s = {" % name)
    out.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    out.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    out.append("    .line_height = %d," % (ascent + descent))
    out.append("    .base_line = %d," % descent)
    out.append("    .subpx = LV_FONT_SUBPX_NONE,")
    out.append("    .underline_position = -1,")
    out.append("    .underline_thickness = 1,")
    out.append("    .dsc = &font_dsc")
    out.append("};")
    path = os.path.join(OUT, name + ".c")
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("%s: %d glyphs, %d bytes of bitmap, line_height %d, base_line %d, digit advance %s" % (
        name + ".c", len(glyphs), index, ascent + descent, descent,
        "/".join("%.2f px" % (a / 16.0) for a in sorted(advances)) or "-"))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--ttf", required=True, help="RobotoFlex-Regular.ttf (the variable font)")
    ap.add_argument("--value-axes", default="wght=500,opsz=48", help="axes of the 48 px readings")
    ap.add_argument("--small-axes", default="wght=400,opsz=14", help="axes of the 20 px reading and the titles")
    args = ap.parse_args()
    value_axes, small_axes = parse_axes(args.value_axes), parse_axes(args.small_axes)
    value_ttf, value_font = instance(args.ttf, value_axes)
    small_ttf, small_font = instance(args.ttf, small_axes)
    write_font("ui_font_vitals_value", value_ttf, value_font, 48, DIGITS, value_axes, "Roboto Flex")
    write_font("ui_font_vitals_small", small_ttf, small_font, 20, DIGITS, small_axes, "Roboto Flex")
    write_font("ui_font_vitals_title", small_ttf, small_font, 14, TITLES, small_axes, "Roboto Flex")


if __name__ == "__main__":
    main()
